// Generates the Excalifont modules of @borrowdale/text from the font files: `npm run fonts`.
//
// Input: packages/text/fonts/excalifont/*.woff2, Excalifont exactly as Excalidraw publishes it,
// split into files by Unicode range (github.com/excalidraw/excalidraw at commit
// 21ffaf4d76bf8554c3ba5561ab8ff41ce89b55fa, packages/excalidraw/fonts/Excalifont). Only the file
// names were changed, to say which range each file holds.
//
// Output, both read from the files' own tables, never typed in by hand:
// - packages/text/src/fonts/excalifont.ts: the metrics, and the code points each file serves.
// - packages/text/src/fonts/excalifont-files.ts: each file as base64, with the code points it serves.
//
// Running it again must leave both files unchanged. Review any diff it produces: a change in the
// metrics changes every measurement.
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';
import wawoff from 'wawoff2';

const FAMILY = 'Excalifont';
// A code point mapped by more than one file is served by the first: the generated unicode-ranges
// never overlap, so the browser and the metrics always pick the same file.
const FILES = ['latin', 'latin-ext', 'greek', 'cyrillic', 'cyrillic-ext', 'marks', 'combining'];
const fontDir = new URL('../packages/text/fonts/excalifont/', import.meta.url);
const srcDir = new URL('../packages/text/src/fonts/', import.meta.url);

const advances = new Map();
const files = [];
let metrics;

for (const name of FILES) {
  const woff2 = readFileSync(new URL(`${name}.woff2`, fontDir));
  const ttf = await wawoff.decompress(woff2);
  const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
  const { hhea } = font.tables;
  const fileMetrics = { unitsPerEm: font.unitsPerEm, ascender: hhea.ascender, descender: hhea.descender };
  metrics ??= fileMetrics;
  if (JSON.stringify(fileMetrics) !== JSON.stringify(metrics)) {
    throw new Error(`${name}.woff2 has different vertical metrics: ${JSON.stringify(fileMetrics)}`);
  }

  const served = [];
  const codePoints = Object.keys(font.tables.cmap.glyphIndexMap).map(Number).sort((a, b) => a - b);
  for (const codePoint of codePoints) {
    if (advances.has(codePoint)) {
      continue;
    }
    const glyph = font.glyphs.get(font.tables.cmap.glyphIndexMap[codePoint]);
    advances.set(codePoint, glyph.advanceWidth);
    served.push(codePoint);
  }
  if (served.length === 0) {
    throw new Error(`${name}.woff2 serves no code point that an earlier file does not already serve`);
  }
  files.push({ name, ranges: toRanges(served), woff2: woff2.toString('base64') });
}

function toRanges(codePoints) {
  const ranges = [];
  for (const codePoint of codePoints) {
    const last = ranges.at(-1);
    if (last && last[1] === codePoint - 1) {
      last[1] = codePoint;
    } else {
      ranges.push([codePoint, codePoint]);
    }
  }
  return ranges;
}

const hex = (codePoint) => `0x${codePoint.toString(16).toUpperCase().padStart(4, '0')}`;
const header = '// Generated by scripts/generate-font.mjs from the Excalifont files. Do not edit.\n';
const sorted = [...advances].sort(([a], [b]) => a - b);
const hexRanges = (ranges) => `[${ranges.map(([first, last]) => `[${hex(first)}, ${hex(last)}]`).join(', ')}]`;

writeFileSync(
  new URL('excalifont.ts', srcDir),
  `${header}import { frozen } from '../frozen.js';
import type { Font } from '../types.js';

/** Excalifont, the default font. Its woff2 files, for embedding or loading, are in \`@borrowdale/text/excalifont-files\`. */
export const excalifont: Font = frozen({
  family: '${FAMILY}',
  unitsPerEm: ${metrics.unitsPerEm},
  ascender: ${metrics.ascender},
  descender: ${metrics.descender},
  advances: {
${sorted.map(([codePoint, advance]) => `    ${hex(codePoint)}: ${advance},`).join('\n')}
  },
  files: [
${files
  .map(
    ({ name, ranges }) => `    // ${name}
    { ranges: ${hexRanges(ranges)} },`,
  )
  .join('\n')}
  ],
});
`,
);

writeFileSync(
  new URL('excalifont-files.ts', srcDir),
  `${header}import { frozen } from '../frozen.js';
import type { FontFiles } from '../types.js';

/*! Excalifont: copyright (c) 2024 by Excalidraw. Excalifont is a trademark of Excalidraw.
 * @license OFL-1.1 (SIL Open Font License 1.1, see OFL.txt in @borrowdale/text) */
/** The Excalifont files as base64 woff2, each with the code points it serves. */
export const excalifontFiles: FontFiles = frozen({
  family: '${FAMILY}',
  files: [
${files
  .map(
    ({ name, ranges, woff2 }) => `    // ${name}
    {
      ranges: ${hexRanges(ranges)},
      woff2: '${woff2}',
    },`,
  )
  .join('\n')}
  ],
});
`,
);

console.log(`${FAMILY}: ${advances.size} code points in ${files.length} files`);
